-- Whether a completion's numbers were taken rather than given.
--
-- A cycle may be closed with a meter reading too old to rely on: the
-- point of the tracker is that the oil gets changed at about five
-- thousand miles, not that the odometer at the moment of service is
-- known exactly, and refusing a rough number left commitments sitting
-- overdue forever with the work already done.
--
-- The error runs the safe way — a stale reading is behind where the
-- meter actually stood, so the next cycle comes due early rather than
-- late — but the record must not imply a precision it does not have. A
-- maintenance history that silently contains a guessed mileage is the
-- quiet kind of lie this design exists to refuse.
ALTER TABLE commitment_completions ADD COLUMN approximate TEXT NOT NULL DEFAULT '';
