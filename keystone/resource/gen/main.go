// Command gen emits TypeScript definitions for the resource schema
// (ADR-W007 A7): the Go structs in keystone/resource stay the single
// source of truth, and the Console consumes the generated
// console/src/generated/resources.ts (committed, like proto/gen; CI
// regenerates and fails on drift). Reflection over the exported spec
// types and their yaml tags — the same names the API's YAML documents
// and any future JSON projection use.
//
// Run from the repo root (or anywhere in the module):
//
//	go run ./resource/gen -out ../console/src/generated/resources.ts
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"reflect"
	"strings"

	"github.com/chickenrat17/wildstone-homelab/keystone/resource"
)

// kindSpecs pairs each kind with its spec type. Adding a kind here is
// part of adding it to the closed registry in resource.go; the drift
// check below fails CI if the two disagree.
var kindSpecs = []struct {
	kind resource.Kind
	spec reflect.Type
}{
	{resource.KindContainer, reflect.TypeOf(resource.ContainerSpec{})},
	{resource.KindVolume, reflect.TypeOf(resource.VolumeSpec{})},
	{resource.KindRoute, reflect.TypeOf(resource.RouteSpec{})},
	{resource.KindDnsRecord, reflect.TypeOf(resource.DnsRecordSpec{})},
	{resource.KindOidcClient, reflect.TypeOf(resource.OidcClientSpec{})},
	{resource.KindLdapGroup, reflect.TypeOf(resource.LdapGroupSpec{})},
	{resource.KindLdapUser, reflect.TypeOf(resource.LdapUserSpec{})},
	{resource.KindIngress, reflect.TypeOf(resource.IngressSpec{})},
	{resource.KindBackupPlan, reflect.TypeOf(resource.BackupPlanSpec{})},
	{resource.KindConfigFile, reflect.TypeOf(resource.ConfigFileSpec{})},
	{resource.KindSeedFile, reflect.TypeOf(resource.SeedFileSpec{})},
	{resource.KindJob, reflect.TypeOf(resource.JobSpec{})},
	{resource.KindSecret, reflect.TypeOf(resource.SecretSpec{})},
	{resource.KindAutomation, reflect.TypeOf(resource.AutomationSpec{})},
}

func main() {
	out := flag.String("out", "", "output path (default: stdout)")
	flag.Parse()

	// The kindSpecs table must cover exactly the closed kind registry —
	// BOTH directions.
	//
	// Only the first was checked, which is the harmless half: a table
	// entry for a kind that does not exist fails to compile anyway. The
	// half that mattered was missing, and it fails silently — a kind
	// added to the registry but not here simply never reaches the
	// Console's types, so the UI cannot render, diff or explain a
	// resource the control plane fully supports, and the codegen drift
	// job stays green while it happens.
	listed := map[resource.Kind]bool{}
	for _, ks := range kindSpecs {
		if !resource.KnownKind(ks.kind) {
			fatal("gen: kind %q not in the resource registry", ks.kind)
		}
		listed[ks.kind] = true
	}
	for _, k := range resource.Kinds() {
		if !listed[k] {
			fatal("gen: kind %q is in the resource registry but not in kindSpecs — "+
				"the Console would never see it; add it above", k)
		}
	}

	var b strings.Builder
	b.WriteString("// Code generated by keystone/resource/gen (ADR-W007 A7). DO NOT EDIT.\n")
	b.WriteString("// Source of truth: keystone/resource. Regenerate:\n")
	b.WriteString("//   cd keystone && go run ./resource/gen -out ../console/src/generated/resources.ts\n\n")

	// Kind union.
	b.WriteString("export type Kind =\n")
	for i, ks := range kindSpecs {
		sep := " |"
		if i == len(kindSpecs)-1 {
			sep = ";"
		}
		fmt.Fprintf(&b, "  %q%s\n", string(ks.kind), sep)
	}
	b.WriteString("\n")
	fmt.Fprintf(&b, "export const API_VERSION = %q;\n\n", resource.ApiVersion)

	// Emit every referenced struct exactly once, dependencies first.
	emitted := map[string]bool{}
	var emit func(t reflect.Type)
	emit = func(t reflect.Type) {
		if emitted[t.Name()] {
			return
		}
		emitted[t.Name()] = true
		// Emit nested struct dependencies first.
		for i := 0; i < t.NumField(); i++ {
			if dep := structElem(t.Field(i).Type); dep != nil {
				emit(*dep)
			}
		}
		fmt.Fprintf(&b, "export interface %s {\n", t.Name())
		for i := 0; i < t.NumField(); i++ {
			f := t.Field(i)
			name, omitempty, skip := yamlName(f)
			if skip {
				continue
			}
			opt := ""
			if omitempty {
				opt = "?"
			}
			fmt.Fprintf(&b, "  %s%s: %s;\n", name, opt, tsType(f.Type))
		}
		b.WriteString("}\n\n")
	}
	emit(reflect.TypeOf(resource.Metadata{}))
	for _, ks := range kindSpecs {
		emit(ks.spec)
	}

	// The document envelope, mirroring the YAML wire shape
	// (apiVersion/kind/metadata/spec).
	b.WriteString("export type Spec =\n")
	specNames := make([]string, 0, len(kindSpecs))
	for _, ks := range kindSpecs {
		specNames = append(specNames, ks.spec.Name())
	}
	for i, n := range specNames {
		sep := " |"
		if i == len(specNames)-1 {
			sep = ";"
		}
		fmt.Fprintf(&b, "  %s%s\n", n, sep)
	}
	b.WriteString("\nexport interface Resource {\n  apiVersion: string;\n  kind: Kind;\n  metadata: Metadata;\n  spec: Spec;\n}\n\n")

	// Per-kind spec mapping, so a narrowed kind gives a narrowed spec.
	b.WriteString("export interface SpecByKind {\n")
	for _, ks := range kindSpecs {
		fmt.Fprintf(&b, "  %s: %s;\n", string(ks.kind), ks.spec.Name())
	}
	b.WriteString("}\n")

	if *out == "" {
		fmt.Print(b.String())
		return
	}
	if err := os.MkdirAll(filepath.Dir(*out), 0o755); err != nil {
		fatal("gen: %v", err)
	}
	if err := os.WriteFile(*out, []byte(b.String()), 0o644); err != nil {
		fatal("gen: %v", err)
	}
}

// yamlName extracts the yaml tag name and omitempty flag for a field.
func yamlName(f reflect.StructField) (name string, omitempty, skip bool) {
	tag := f.Tag.Get("yaml")
	if tag == "-" || tag == "" {
		return "", false, true
	}
	parts := strings.Split(tag, ",")
	name = parts[0]
	for _, p := range parts[1:] {
		if p == "omitempty" {
			omitempty = true
		}
	}
	return name, omitempty, false
}

// structElem returns the struct type reachable through t (direct, pointer,
// or slice element), or nil.
func structElem(t reflect.Type) *reflect.Type {
	switch t.Kind() {
	case reflect.Pointer, reflect.Slice:
		return structElem(t.Elem())
	case reflect.Struct:
		return &t
	}
	return nil
}

// tsType maps a Go field type to its TypeScript type.
func tsType(t reflect.Type) string {
	switch t.Kind() {
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
		reflect.Float32, reflect.Float64:
		return "number"
	case reflect.Slice:
		return tsType(t.Elem()) + "[]"
	case reflect.Map:
		return fmt.Sprintf("Record<%s, %s>", tsType(t.Key()), tsType(t.Elem()))
	case reflect.Pointer:
		return tsType(t.Elem())
	case reflect.Struct:
		return t.Name()
	default:
		fatal("gen: unmapped Go type %s", t)
		return ""
	}
}

func fatal(format string, args ...any) {
	fmt.Fprintf(os.Stderr, format+"\n", args...)
	os.Exit(1)
}
