-- 0082: the opaque task handle (ADR-W039 §3.1 principle 4, §3.4 steps
-- 1–2, §4 item 2; Phase 2a of the migration plan in §8).
--
-- Every capability, memory and work call a runtime makes carries a
-- Wildstone-issued handle naming the task it acts within. Its form is
-- `<taskID>.<secret>`: the task id is public and is what audit rows
-- key on; the secret is what Wildstone checks. Only a digest of the
-- secret is kept here, so a database read cannot mint a handle.
--
-- One live handle per task, on the task row rather than in a side
-- table: a handle is a property of the task's admission — the Person,
-- Connection, audience and Butler it resolves to are the task's own
-- columns — and re-issuing replaces it. '' means no handle has been
-- issued (every task before this migration) or it was withdrawn, and
-- both resolve to a refusal.
--
-- Lookups go by the public task id, which is the primary key, so no
-- index is needed on the digest.
ALTER TABLE butler_tasks ADD COLUMN handle_hash TEXT NOT NULL DEFAULT '';
